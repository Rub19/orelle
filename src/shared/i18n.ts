const DICTS = { fr: fr as Record<StringKey, string>, en };

export type Translator = (key: StringKey, vars?: Record<string, string | number>) => string;

export function createTranslator(lang: 'fr' | 'en'): Translator {
  const dict = DICTS[lang];
  return (key, vars) => {
    let s = dict[key] ?? DICTS.fr[key] ?? key;
    if (vars) for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v));
    return s;
  };
}

export function resolveLanguage(pref: 'auto' | 'fr' | 'en', systemLocale: string): 'fr' | 'en' {
  if (pref !== 'auto') return pref;
  return systemLocale.toLowerCase().startsWith('fr') ? 'fr' : 'en';
}
